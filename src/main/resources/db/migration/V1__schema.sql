CREATE TABLE users (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name            VARCHAR(120) NOT NULL,
    email                VARCHAR(160) NOT NULL UNIQUE,
    phone                VARCHAR(40),
    password_hash        VARCHAR(100) NOT NULL,
    role                 VARCHAR(20)  NOT NULL,
    must_change_password BOOLEAN      NOT NULL DEFAULT TRUE,
    active               BOOLEAN      NOT NULL DEFAULT TRUE,
    notes                TEXT,
    created_at           TIMESTAMP    NOT NULL
);

CREATE TABLE course (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug               VARCHAR(60)  NOT NULL UNIQUE,
    title              VARCHAR(120) NOT NULL,
    duration_months    INT          NOT NULL,
    sort_order         INT          NOT NULL,
    -- Students of a course also get full access to the included course (Advanced includes Essentials).
    includes_course_id BIGINT REFERENCES course (id)
);

CREATE TABLE course_month (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id    BIGINT       NOT NULL REFERENCES course (id),
    month_number INT          NOT NULL,
    title        VARCHAR(200) NOT NULL,
    description  TEXT,
    UNIQUE (course_id, month_number)
);

CREATE TABLE lesson (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    month_id   BIGINT       NOT NULL REFERENCES course_month (id),
    sort_order INT          NOT NULL DEFAULT 0,
    title      VARCHAR(200) NOT NULL,
    content    TEXT,
    video_url  VARCHAR(500),
    preview    BOOLEAN      NOT NULL DEFAULT FALSE,
    published  BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP    NOT NULL,
    updated_at TIMESTAMP    NOT NULL
);

CREATE TABLE lesson_attachment (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id     BIGINT       NOT NULL REFERENCES lesson (id) ON DELETE CASCADE,
    original_name VARCHAR(255) NOT NULL,
    stored_name   VARCHAR(100) NOT NULL,
    content_type  VARCHAR(120),
    size_bytes    BIGINT       NOT NULL,
    created_at    TIMESTAMP    NOT NULL
);

CREATE TABLE enrollment (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT    NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    course_id  BIGINT    NOT NULL REFERENCES course (id),
    start_date DATE      NOT NULL,
    end_date   DATE,
    active     BOOLEAN   NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL,
    UNIQUE (user_id, course_id)
);

CREATE TABLE lesson_progress (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT    NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    lesson_id    BIGINT    NOT NULL REFERENCES lesson (id) ON DELETE CASCADE,
    completed_at TIMESTAMP NOT NULL,
    UNIQUE (user_id, lesson_id)
);

CREATE TABLE blog_post (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug         VARCHAR(200) NOT NULL UNIQUE,
    title        VARCHAR(200) NOT NULL,
    summary      VARCHAR(500),
    cover_image  VARCHAR(300),
    content      TEXT,
    lang         VARCHAR(5)   NOT NULL,
    status       VARCHAR(20)  NOT NULL,
    published_at TIMESTAMP,
    created_at   TIMESTAMP    NOT NULL,
    updated_at   TIMESTAMP    NOT NULL
);

CREATE TABLE inquiry (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(120)  NOT NULL,
    email           VARCHAR(160)  NOT NULL,
    phone           VARCHAR(40),
    course_interest VARCHAR(60),
    message         VARCHAR(2000),
    status          VARCHAR(20)   NOT NULL,
    admin_note      VARCHAR(1000),
    created_at      TIMESTAMP     NOT NULL
);

CREATE INDEX idx_lesson_month ON lesson (month_id);
CREATE INDEX idx_enrollment_user ON enrollment (user_id);
CREATE INDEX idx_progress_user ON lesson_progress (user_id);
CREATE INDEX idx_blog_status ON blog_post (status, published_at);
